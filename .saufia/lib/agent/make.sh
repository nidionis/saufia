# agent::make <name> [description] — an agent writes a new agent.
agent::make() {
# shlould be a sub function "prompting" untill the project does not have editor yet
# agent::make::prompting()
  local name="$1" desc="${2:-$name}"
  local dir="$SAUFIA_CTX/agents/$name"
  mkdir -p "$dir"
  agent::load "cold/coldiest"
  agent::ask "Write a terse system prompt for an agent that: $desc
Output the prompt text only." > "$dir/prompt"
  agent::ask "Pick tuning vars (ex: AGENT_TEMPERATURE AGENT_TOP_K AGENT_NUM_PREDICT)
for an agent that: $desc. Output KEY=value lines only, max 3." > "$dir/config"
  echo "agent: $name (generated by coldiest)"
}
# BTW We prefer TEMPERATURE at AGENT_TEMPERATURE (globally in the code, AGENT is quite omnipotent)
