# agent::make <name> [description] — an agent writes a new agent.
agent::make() {
  local name="$1" desc="${2:-$name}"
  local dir="$SAUFIA_CTX/agents/$name"
  mkdir -p "$dir"
  agent::load "cold/coldiest"
  agent::ask "Write a terse system prompt (max 3 lines) for an agent that: $desc
Output the prompt text only." > "$dir/prompt"
  agent::ask "Pick tuning vars (only from AGENT_TEMPERATURE AGENT_TOP_K AGENT_NUM_PREDICT)
for an agent that: $desc. Output KEY=value lines only, max 3." > "$dir/config"
  echo "agent: $name (generated by coldiest)"
}
